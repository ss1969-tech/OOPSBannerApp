/*
 * OOPSBannerApp UC2 – Banner Display Application
 * Displays "OOPS" using ASCII art with * and spaces
 * Using + operator for string concatenation
 */

public class OOPSBannerApp {

    public static void main(String[] args) {

        System.out.println("  ***   " + "  ***   " + " *****  " + " *****  ");
        System.out.println(" *   *  " + " *   *  " + " *    * " + " *      ");
        System.out.println("*     * " + "*     * " + " *    * " + " *      ");
        System.out.println("*     * " + "*     * " + " *****  " + "  ***** ");
        System.out.println("*     * " + "*     * " + " *      " + "       *");
        System.out.println(" *   *  " + " *   *  " + " *      " + " *     *");
        System.out.println("  ***   " + "  ***   " + " *      " + "  ***** ");
    }
}